/*
 * dmr_rctl_cfg.h — конфігураційний блок "RCTL" (бінарний перемикач "приймати команди
 * віддаленого керування") в OpenGD77 custom-data флеші. Модель за зразком MSGC-блоку
 * SMS (dmr_sms.c): пише CHIRP-модуль/PC-утиліта, прошивка лише читає — жодного запису
 * назад із самої рації, тож баг у прошивці не може зіпсувати/підмінити цей прапорець.
 *
 * ВИПРАВЛЕНО 2026-09-03 (пряма вказівка користувача, за зразком Motorola/Hytera):
 * жодного окремого списку довірених ID тут більше немає — єдина межа довіри це
 * увімк/вимк плюс той самий AES-ключ каналу, що й голос/SMS. Див. dmr_rctl_pdu.h.
 *
 * Не плутати з crypto/dmr_rctl_pdu.h — той файл суто логіка (пакування PDU,
 * enabled-перевірка й anti-replay кеш у RAM) і навмисно не залежить від STM32/флеш-API,
 * щоб лишатись тестованим на хості. Цей файл — тонкий місток між ним і реальною
 * флешкою кодплагу.
 */
#ifndef _OPENGD77_DMR_RCTL_CFG_H_
#define _OPENGD77_DMR_RCTL_CFG_H_

#include "crypto/dmr_rctl_pdu.h"
#include <stdint.h>

#if defined(ENABLE_DMR_DATA) && defined(ENABLE_AES)

/* Повертає єдиний рантайм-gate (кеш anti-replay живе лише в RAM, у флеш не
 * пишеться). Ледаче (пере)завантажується з блоку "RCTL" при першому виклику.
 * Відсутній/пошкоджений блок -> gate лишається вимкненим (enabled=0) —
 * fail closed, так само, якби цієї фічі в збірці не було взагалі. */
dmr_rctl_gate_t *dmrRctlGate(void);

/* Примусово перечитати блок "RCTL" при наступному dmrRctlGate()/dmrRctlConfigEnabled()
 * (напр. якщо кодплаг переписали через CPS у тому ж сеансі; тестам теж зручно). */
void dmrRctlConfigReload(void);

/* Дешева перевірка "чи взагалі є сенс щось робити" без побудови самого gate:
 * 1, якщо блок валідний і enabled=1; інакше 0. */
int dmrRctlConfigEnabled(void);

/* Записати новий стан "enabled" у блок "RCTL" (2026-09-03: тепер джерело запису не
 * лише CHIRP/PC-утиліта rctl_config.py, а й сама рація - меню Options>RCTL access,
 * menuRCTLConfig.c, за зразком того, як menuAESKeys.c пише AES-ключі прямо з рації).
 * Викликач має заздалегідь один раз викликати dmrAesEnsureCustomDataRegion()
 * (crypto/dmr_aes_hook.h), якщо custom-data регіон ще не ініціалізовано - та сама,
 * спільна для всього регіону операція, що й для AES-ключів/тем/повідомлень.
 * Повертає 1 при успішному записі, 0 при помилці флеш-запису. Ефект - негайний:
 * функція сама викликає dmrRctlConfigReload(). */
int dmrRctlConfigSetEnabled(int enabled);

/* Маска дозволених команд (біти DMR_RCTL_ALLOW_* з crypto/dmr_rctl_pdu.h).
 * Повертає 0, якщо головний перемикач вимкнено -- тобто вимкнений "Доступ RCTL"
 * перекриває будь-які окремі дозволи. */
uint8_t dmrRctlAllowMask(void);

/* Чи дозволено ВИКОНАТИ цю команду на цій рації. Невідомий код команди -> 0
 * (fail closed: майбутня команда не має отримати дозвіл від старої прошивки).
 *
 * Це НЕ про шифрування. Ключ каналу вирішує, чи команду взагалі буде прочитано;
 * ця функція -- чи рація погодиться її виконати. На відкритому каналі, де
 * підтвердити відправника нічим, вона лишається єдиною межею. */
int dmrRctlCommandAllowed(uint8_t cmd);

/* Маска дозволів БЕЗ огляду на головний перемикач -- для екрана редагування: інакше,
 * вимкнувши доступ, користувач втрачав би виставлені дозволи, щойно зайшов у меню. */
uint8_t dmrRctlConfigAllowRaw(void);

/* Записати нову маску дозволів у блок "RCTL". Повертає 1 при успіху. */
int dmrRctlConfigSetAllow(uint8_t mask);

/* Тривалість відповіді форка-цілі на Monitor (сек). Ніколи 0: якщо не виставлено --
 * повертає типове (30 с). Запис -- dmrRctlConfigSetMonitorSecs (меню / ПК). */
uint8_t dmrRctlMonitorSecs(void);
int dmrRctlConfigSetMonitorSecs(uint8_t secs);

/* Записати поточні лічильники anti-replay у флеш (блок "RCTS", окремий від "RCTL").
 * Викликати ПІСЛЯ того, як dmr_rctl_gate_check() прийняв команду, і ДО того, як
 * команду виконано -- інакше знеструмлення між дією і записом лишає вікно на один
 * повтор. Повертає 1 при успіху. */
int dmrRctlGatePersist(void);

/* Наступний номер послідовності для ВІДПРАВКИ. Монотонний ЧЕРЕЗ ПЕРЕЗАВАНТАЖЕННЯ:
 * номери видаються пачками, у флеш пишеться лише верхня межа (див. коментар у
 * dmr_rctl_cfg.c). Повертає 0, якщо зарезервувати діапазон не вдалося -- тоді
 * відправку треба скасувати, а не слати команду з непевним номером. */
uint32_t dmrRctlNextTxSeq(void);

/* Стан "рація заблокована" (stun/revive), у флеш-блоці RCTS -- переживає перезавантаження.
 * dmrRctlIsInhibited() = 1, якщо рацію заблоковано. dmrRctlSetInhibited() пише у флеш
 * (1 при успіху). Знімається Enable по ефіру або кабелем (recovery). */
int dmrRctlIsInhibited(void);
int dmrRctlSetInhibited(int on);

#endif /* ENABLE_DMR_DATA && ENABLE_AES */
#endif /* _OPENGD77_DMR_RCTL_CFG_H_ */
