/*
 * slogans_ua.h -- гасла на екрані вмикання (uiSplashScreen.c) та вимкнення
 * (uiPowerOff.c) рації.
 *
 * ВАЖЛИВО: цей файл, як і решта *_ua.h у цій теці, має кодування cp1251 -- саме
 * так шрифт HX8353E_charset_UA.h трактує коди 192-255. Не зберігати в UTF-8.
 *
 * Літери "Ї" (0xAF) та "І" (0xB2) лежать ПОЗА основним кириличним діапазоном
 * 192-255, тому перед додаванням цих рядків гліфи перевірено просто в таблиці
 * шрифту: обидва на місці й намальовані правильно.
 *
 * Рядки не в stringsTable_t навмисно: вони специфічні саме для української
 * збірки, англійського відповідника не мають і CPS їх не читає.
 */
#ifndef USER_INTERFACE_LANGUAGES_SLOGANS_UA_H_
#define USER_INTERFACE_LANGUAGES_SLOGANS_UA_H_

/* 14 символів = 112px у FONT_SIZE_3 (8x16) -- вміщається в 160px екрана */
#define SLOGAN_POWER_ON          "СЛАВА УКРАЇНІ!"
/* 13 символів = 104px у FONT_SIZE_3 -- вміщається у рамку екрана вимкнення */
#define SLOGAN_POWER_OFF         "ГЕРОЯМ СЛАВА!"

#endif /* USER_INTERFACE_LANGUAGES_SLOGANS_UA_H_ */
